"""Pydantic models for tool inputs and outputs, all importable from here.

Conventions every domain module follows:

* Inputs are named ``*Spec`` (``ContractSpec``, ``OrderSpec``, ``ScannerSpec``) and forbid
  unknown fields. The algo strategies (``AdaptiveAlgo``...) and ``SoftDollarTierRef`` are
  inputs too, named for what they select.
* Outputs are named for what they describe (``HealthReport``, ``ServerTime``,
  ``OrderPreview``). A model that mirrors one IBKR object, record or setting carries an
  ``Out`` suffix (``ContractOut``, ``PositionOut``, ``QuoteOut``, ``WhatIfOut``,
  ``ServerLogLevelOut``), which also keeps it apart from the ib_async class
  (``Contract``, ``Position``) or the input type (``ServerLogLevel``) of the same name.
* Services return these models, never ib_async objects. Missing numbers are ``None``
  (never NaN), datetimes are timezone-aware, account-scoped results carry ``account``,
  and list results that honour a ``limit`` subclass :class:`~.common.Truncatable`.

Every model and type below is re-exported from its domain module
(``ib_gateway_mcp.models.orders``, ...), where the constants and helpers live too.
"""

