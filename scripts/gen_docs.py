"""Generate the public tool reference, ``docs/tools.md``, from the tool registry.

Every tool of every toolset, with its tier, description and parameters as MCP clients
see them, the fields of the nested input types (``ContractSpec``, ``OrderSpec``...), and
the service method behind each tool for library users. (``docs/coverage.md``, the TWS
API coverage table, is edited by hand; ``tests/unit/test_docs.py`` checks that it names
every tool.)

Usage::

    uv run python scripts/gen_docs.py            # write docs/tools.md
    uv run python scripts/gen_docs.py --check    # exit 1 if it is out of date

``tests/unit/test_docs.py`` fails when ``docs/tools.md`` no longer matches the registry.
"""

